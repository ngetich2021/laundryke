// Minimal service worker: just enough for PWA installability. Deliberately
// does not cache dynamic/API/auth responses, only falls back to a cached
// copy when the network is unreachable (best-effort offline support).
const CACHE_NAME = "drwash-v1";

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  // Never touch auth/API/action traffic — only cache plain page/asset GETs.
  if (event.request.method !== "GET" || url.pathname.startsWith("/api/")) return;

  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
